#IDENTITY OPERATOR

a=[3,4,5,7]
b=a
result1=a is b #IS operator
answer1=a is not b #IS not operator
print("the output of ",a,"is",b,":",result1)
print("the output of ",a,"is not",b,":",answer1)

c=[0,9,8,7,6]
d=[0,9,8,7,6]
